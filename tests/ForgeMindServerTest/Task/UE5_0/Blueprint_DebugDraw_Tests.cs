namespace ForgeMindServer.Test.Task.UE5_0;

using Task = System.Threading.Tasks.Task;

// =========================================================================
// No. 14 - Blueprint Debug Draw (UE 5.0) - from Tasks/UE_5.0/blueprint-debug-draw.md
// =========================================================================

public sealed class Blueprint_DebugDraw : ITestCase
{
    public string Name => "Blueprint Debug Draw (UE 5.0)";
    public string? Group => "UE5.0";
    public int Order => 14;

    public async Task Run(TestContext ctx)
    {
        // -- Support status probe conclusion (collaboration spec point 6) --
        // Engine signature review (UE 5.0.3 source KismetSystemLibrary.h L1461-1510, all
        // KismetSystemLibrary static functions, meta DevelopmentOnly):
        // - DrawDebugLine(LineStart, LineEnd, LineColor, Duration, Thickness)
        // - DrawDebugSphere(Center, Radius, Segments, LineColor, Duration, Thickness)
        // - DrawDebugString(TextLocation, Text, TestBaseActor, TextColor, Duration)
        // Color params are FLinearColor: doc's Color=Red/Green falls to LinearColor
        // import-text pin defaults. Struct ImportText must have parentheses -- UE 5.0.3
        // Class.cpp UScriptStruct::ImportText reports "Missing opening parenthesis" for
        // text without '(' ("(X=0,Y=0,Z=0)" / "(R=1,G=0,B=0,A=1)").
        // DSL `new Vector(x,y,z)` / `Color.Red` call arg forms are pending implementation --
        // test is spec; DSL gaps exposed by test failures are pending implementation requirements.

        // -- Subtask 1: DrawDebugLine --
        // MCP steps: create blueprint -> function Draw -> DrawDebugLine(LineStart=(0,0,0),
        //         LineEnd=(100,0,0), LineColor=Red, Duration=1.0)
        const string a1 = "/Game/Tests/UE5_0/Dbg_Line_A";
        BlueprintTestHelper.CreateBlueprintActor(ctx, a1);
        var f1 = BlueprintTestHelper.CreateFunction(ctx, a1, "Draw");
        var line1 = BlueprintTestHelper.AddNode(ctx, a1, "Draw", "DrawDebugLine", 300, 0, "KismetSystemLibrary");
        // struct pin default format per intersection of engine three consumer ends (20261001_2223 second run location):
        // - Vector (SplitPin L7141 comma split + Atof / RecombinePin L7245 official writeback):
        //   bare digits "100, 0, 0" -- same format as AutogeneratedDefaultValue "0, 0, 0";
        //   "X=.."/"(X=..)" compiles but UI splits sub-pins Atof yields 0.
        // - LinearColor (compile literal VMBackend L897 ImportText / RecombinePin
        //   L7273 LC.ToString()): "(R=1,G=0,B=0,A=1)" with parentheses; no parentheses
        //   reports "Missing opening parenthesis" at compile (goes through GLog, not node messages).
        BlueprintTestHelper.SetPinDefault(ctx, a1, line1.nodeId, "LineStart", "0, 0, 0");
        BlueprintTestHelper.SetPinDefault(ctx, a1, line1.nodeId, "LineEnd", "100, 0, 0");
        BlueprintTestHelper.SetPinDefault(ctx, a1, line1.nodeId, "LineColor", "(R=1,G=0,B=0,A=1)");
        BlueprintTestHelper.SetPinDefault(ctx, a1, line1.nodeId, "Duration", "1.0");
        BlueprintTestHelper.Connect(ctx, a1, f1.entryId, "then", line1.nodeId, "execute");
        BlueprintTestHelper.Connect(ctx, a1, line1.nodeId, "then", f1.resultId, "execute");
        BlueprintTestHelper.CompileAndSave(ctx, a1);
        BlueprintTestHelper.VerifyIrSnapshot(ctx, a1);

        // DSL path (from task doc; doc's Start/End/Color semantics correspond to engine real pin
        // names LineStart/LineEnd/LineColor, positional order consistent)
        BlueprintTestHelper.ApplyDsl(ctx, "");
        BlueprintTestHelper.VerifyIrSnapshot(ctx, "/Game/Tests/UE5_0/Dbg_Line_B");

        // -- Subtask 2: DrawDebugSphere --
        // MCP steps: create blueprint -> function Draw -> GetActorLocation -> Center,
        //         Radius=50, Segments=12, LineColor=Green, Duration=2.0
        const string a2 = "/Game/Tests/UE5_0/Dbg_Sphere_A";
        BlueprintTestHelper.CreateBlueprintActor(ctx, a2);
        var f2 = BlueprintTestHelper.CreateFunction(ctx, a2, "Draw");
        // Blueprint-callable UFUNCTION real name is K2_GetActorLocation (Actor.h L1185,
        // DisplayName "Get Actor Location"; C++ GetActorLocation is inline).
        // When name not found, silently creates 0-pin node via bSelfMember (first run 20261001_2118).
        var loc2 = BlueprintTestHelper.AddNode(ctx, a2, "Draw", "K2_GetActorLocation", 100, 200);
        var sph2 = BlueprintTestHelper.AddNode(ctx, a2, "Draw", "DrawDebugSphere", 300, 0, "KismetSystemLibrary");
        BlueprintTestHelper.Connect(ctx, a2, loc2.nodeId, "ReturnValue", sph2.nodeId, "Center");
        BlueprintTestHelper.SetPinDefault(ctx, a2, sph2.nodeId, "Radius", "50.0");
        BlueprintTestHelper.SetPinDefault(ctx, a2, sph2.nodeId, "Segments", "12");
        BlueprintTestHelper.SetPinDefault(ctx, a2, sph2.nodeId, "LineColor", "(R=0,G=1,B=0,A=1)");
        BlueprintTestHelper.SetPinDefault(ctx, a2, sph2.nodeId, "Duration", "2.0");
        BlueprintTestHelper.Connect(ctx, a2, f2.entryId, "then", sph2.nodeId, "execute");
        BlueprintTestHelper.Connect(ctx, a2, sph2.nodeId, "then", f2.resultId, "execute");
        BlueprintTestHelper.CompileAndSave(ctx, a2);
        BlueprintTestHelper.VerifyIrSnapshot(ctx, a2);

        // DSL path (from task doc; arg positional order consistent with engine
        // signature Center/Radius/Segments/LineColor/Duration)
        BlueprintTestHelper.ApplyDsl(ctx, "");
        BlueprintTestHelper.VerifyIrSnapshot(ctx, "/Game/Tests/UE5_0/Dbg_Sphere_B");

        // -- Subtask 3: DrawDebugString --
        // MCP steps: create blueprint -> function Draw -> GetActorLocation -> TextLocation,
        //         Text="hi", Duration=1.0
        const string a3 = "/Game/Tests/UE5_0/Dbg_Str_A";
        BlueprintTestHelper.CreateBlueprintActor(ctx, a3);
        var f3 = BlueprintTestHelper.CreateFunction(ctx, a3, "Draw");
        var loc3 = BlueprintTestHelper.AddNode(ctx, a3, "Draw", "K2_GetActorLocation", 100, 200);
        var str3 = BlueprintTestHelper.AddNode(ctx, a3, "Draw", "DrawDebugString", 300, 0, "KismetSystemLibrary");
        BlueprintTestHelper.Connect(ctx, a3, loc3.nodeId, "ReturnValue", str3.nodeId, "TextLocation");
        BlueprintTestHelper.SetPinDefault(ctx, a3, str3.nodeId, "Text", "hi");
        BlueprintTestHelper.SetPinDefault(ctx, a3, str3.nodeId, "Duration", "1.0");
        BlueprintTestHelper.Connect(ctx, a3, f3.entryId, "then", str3.nodeId, "execute");
        BlueprintTestHelper.Connect(ctx, a3, str3.nodeId, "then", f3.resultId, "execute");
        BlueprintTestHelper.CompileAndSave(ctx, a3);
        BlueprintTestHelper.VerifyIrSnapshot(ctx, a3);

        // DSL path (doc form DrawDebugString("hi", GetActorLocation(), 1.0f) positional
        // args don't match engine signature (TextLocation, Text, TestBaseActor, TextColor,
        // Duration) -- corrected by engine arg order, TestBaseActor/TextColor fall to engine
        // defaults (null/White), equivalent to MCP path asset content)
        BlueprintTestHelper.ApplyDsl(ctx, "");
        BlueprintTestHelper.VerifyIrSnapshot(ctx, "/Game/Tests/UE5_0/Dbg_Str_B");

        await Task.CompletedTask;
    }
}
