using Task = System.Threading.Tasks.Task;

// =========================================================================
// No. 31 - Blueprint Class Defaults (UE 5.0) - from Tasks/UE_5.0/blueprint-class-defaults.md
//
// Probe (collaboration spec point 6):
// - Doc requires a prerequisite target blueprint (BP_Enemy with DefaultHP : int /
//   DefaultName : string) -- created here in every round, same pattern as
//   Blueprint_ConstructObject_Tests' MyData.
// - **The GetClassDefaults step is attempted as written, not skipped**
//   (collaboration spec point 6: "When probing finds unsupported, do not detour or
//   skip tasks — write the test directly assuming supported."). The bridge's native flow node vocabulary
//   (CreateNativeFlowNode, ForgeMindBridgeClient_BlueprintGraph.cpp:148-233) currently has
//   no `GetClassDefaults` entry, so today this case fails with
//   "Failed to create native flow node 'GetClassDefaults'" -- that failure *is* the
//   requirement signal for both the A side and the DSL side.
// - UK2Node_GetClassDefaults exists in the engine (K2Node_GetClassDefaults.h:16, title
//   "Get Class Defaults", K2Node_GetClassDefaults.cpp:236). Its input pin is `Class` (PC_Class,
//   cpp:19/244) and its outputs are **one pin per property**, generated by
//   FClassDefaultsOptionalPinManager::CreateVisiblePins (cpp:486-492) -- so the doc's
//   "GetClassDefaults(BP_Enemy) -> Break -> DefaultHP" shape does not exist: there is no
//   struct output and nothing to Break. This test passes the target class through
//   `targetClass` (same payload key Cast uses for its TargetType, and the helper already
//   forwards it), matching the node's real Class pin semantics.
// - The node is pure (no exec pins), so the execution chain runs entry -> consumer -> result
//   (same shape as Blueprint_Ease_Tests' Ease node).
// - DSL side: doc writes `GetClassDefaults<BP_Enemy>()` (a generic call) and declares
//   BP_Enemy out of thin air. Copied as written. Latest run (TestRuns/20261008_2046) shows
//   ERROR FM1002 -- the translator resolves calls against the engine function scan index and
//   GetClassDefaults is a pure K2 node with no backing UFunction, so it can never resolve as
//   a normal call: the DSL needs a dedicated construct. Test is spec.
//
// Note: mis-touch comparison (VerifyIrSnapshot) inserted per user instruction,
// covering all A/B sides after visual confirmation of TestRuns/20261009_1609.
// =========================================================================

public sealed class Blueprint_ClassDefault : ITestCase
{
    public string Name => "Blueprint Class Defaults (UE 5.0)";
    public string? Group => "UE5.0";
    public int Order => 31;

    /// <summary>
    /// Prerequisite target blueprint for all three subtasks: the class whose CDO is read.
    /// Recreated every round because GroupLifecycle wipes Content/Tests.
    /// </summary>
    private static void CreatePrerequisiteEnemy(TestContext ctx)
    {
        const string enemy = "/Game/Tests/UE5_0/BP_Enemy";
        BlueprintTestHelper.CreateBlueprint(ctx, enemy, "Actor");
        BlueprintTestHelper.AddVariable(ctx, enemy, "DefaultHP", "int", 100);
        BlueprintTestHelper.AddVariable(ctx, enemy, "DefaultName", "string", "Enemy");
        BlueprintTestHelper.CompileAndSave(ctx, enemy);
    }

    public async Task Run(TestContext ctx)
    {
        // -- Subtask 1: read a class default property --
        // MCP steps: CDO_Read_A (Extends Actor) + function Get()
        //   -> GetClassDefaults(BP_Enemy).DefaultName -> PrintString
        //   (DefaultName is FString → PrintString.InString is FString: type-matched,
        //    no autocast needed. DefaultHP is int → would need autocast which the
        //    bridge's programmatic TryCreateConnection does not do; that path is
        //    exercised by the DSL B side which goes through bridge autocast.)
        CreatePrerequisiteEnemy(ctx);
        const string a1 = "/Game/Tests/UE5_0/CDO_Read_A";
        BlueprintTestHelper.CreateBlueprintActor(ctx, a1);
        var f1 = BlueprintTestHelper.CreateFunction(ctx, a1, "Get");
        var cdo1 = BlueprintTestHelper.AddNode(ctx, a1, "Get", "GetClassDefaults", 300, 0,
            targetClass: "BP_Enemy");
        var print1 = BlueprintTestHelper.AddNode(ctx, a1, "Get", "PrintString", 600, 0,
            "KismetSystemLibrary");
        BlueprintTestHelper.Connect(ctx, a1, cdo1.nodeId, "DefaultName", print1.nodeId, "InString");
        BlueprintTestHelper.Connect(ctx, a1, f1.entryId, "then", print1.nodeId, "execute");
        BlueprintTestHelper.Connect(ctx, a1, print1.nodeId, "then", f1.resultId, "execute");
        BlueprintTestHelper.CompileAndSave(ctx, a1);
        BlueprintTestHelper.VerifyIrSnapshot(ctx, a1);

        // DSL path (copied from task doc)
        BlueprintTestHelper.ApplyDsl(ctx, "");
        BlueprintTestHelper.VerifyIrSnapshot(ctx, "/Game/Tests/UE5_0/CDO_Read_B");

        // -- Subtask 2: initialize an instance from the class default --
        // MCP steps: CDO_Init_A (Extends Actor) + HP : int
        //   Event BeginPlay -> GetClassDefaults(BP_Enemy).DefaultHP -> Set(HP)
        const string a2 = "/Game/Tests/UE5_0/CDO_Init_A";
        BlueprintTestHelper.CreateBlueprintActor(ctx, a2);
        BlueprintTestHelper.AddVariable(ctx, a2, "HP", "int", 0);
        var ev2 = BlueprintTestHelper.AddNode(ctx, a2, "EventGraph", "ReceiveBeginPlay", 0, 0);
        var cdo2 = BlueprintTestHelper.AddNode(ctx, a2, "EventGraph", "GetClassDefaults", 300, 0,
            targetClass: "BP_Enemy");
        var set2 = BlueprintTestHelper.AddNode(ctx, a2, "EventGraph", "HP", 600, 0, kind: "setter");
        BlueprintTestHelper.Connect(ctx, a2, cdo2.nodeId, "DefaultHP", set2.nodeId, "HP");
        BlueprintTestHelper.Connect(ctx, a2, ev2.nodeId, "then", set2.nodeId, "execute");
        BlueprintTestHelper.CompileAndSave(ctx, a2);
        BlueprintTestHelper.VerifyIrSnapshot(ctx, a2);

        // DSL path (copied from task doc)
        BlueprintTestHelper.ApplyDsl(ctx, "");
        BlueprintTestHelper.VerifyIrSnapshot(ctx, "/Game/Tests/UE5_0/CDO_Init_B");


        await Task.CompletedTask;
    }
}