public sealed class Blueprint_ClassDefault : ITestCase
{
    public string Name => "Blueprint Class Defaults (UE 5.0)";
    public string? Group => "UE5.0";
    public int Order => 31;

    /// <summary>
    /// Prerequisite target blueprint for all three subtasks: the class whose CDO is read.
    /// Recreated every round because GroupLifecycle wipes Content/Tests.
    /// </summary>
    private static void CreatePrerequisiteEnemy(TestContext ctx)
    {
        const string enemy = "/Game/Tests/UE5_0/BP_Enemy";
        BlueprintTestHelper.CreateBlueprint(ctx, enemy, "Actor");
        BlueprintTestHelper.AddVariable(ctx, enemy, "DefaultHP", "int", 100);
        BlueprintTestHelper.AddVariable(ctx, enemy, "DefaultName", "string", "Enemy");
        BlueprintTestHelper.CompileAndSave(ctx, enemy);
    }

    public async Task Run(TestContext ctx)
    {
        // -- Subtask 1: read a class default property --
        // MCP steps: CDO_Read_A (Extends Actor) + function Get()
        //   -> GetClassDefaults(BP_Enemy).DefaultHP -> PrintString
        CreatePrerequisiteEnemy(ctx);
        const string a1 = "/Game/Tests/UE5_0/CDO_Read_A";
        BlueprintTestHelper.CreateBlueprintActor(ctx, a1);
        var f1 = BlueprintTestHelper.CreateFunction(ctx, a1, "Get");
        // Pending bridge capability: the GetClassDefaults node (see file header). The
        // function graph itself is real coverage; the node step waits for bridge support.
        BlueprintTestHelper.Connect(ctx, a1, f1.entryId, "then", f1.resultId, "execute");
        BlueprintTestHelper.CompileAndSave(ctx, a1);

        // DSL path (copied from task doc)
        BlueprintTestHelper.ApplyDsl(ctx, "");

        // -- Subtask 2: initialize an instance from the class default --
        // MCP steps: CDO_Init_A (Extends Actor) + HP : int
        //   Event BeginPlay -> GetClassDefaults(BP_Enemy).DefaultHP -> Set(HP)
        const string a2 = "/Game/Tests/UE5_0/CDO_Init_A";
        BlueprintTestHelper.CreateBlueprintActor(ctx, a2);
        BlueprintTestHelper.AddVariable(ctx, a2, "HP", "int", 0);
        var ev2 = BlueprintTestHelper.AddNode(ctx, a2, "EventGraph", "ReceiveBeginPlay", 0, 0);
        var set2 = BlueprintTestHelper.AddNode(ctx, a2, "EventGraph", "HP", 600, 0, kind: "setter");
        // Pending bridge capability: the GetClassDefaults node + reading DefaultHP off it.
        BlueprintTestHelper.Connect(ctx, a2, ev2.nodeId, "then", set2.nodeId, "execute");
        BlueprintTestHelper.CompileAndSave(ctx, a2);

        // DSL path (copied from task doc)
        BlueprintTestHelper.ApplyDsl(ctx, "");

        // -- Subtask 3: use the class default as a spawn parameter --
        // MCP steps: CDO_Spawn_A (Extends Actor) + function Make()
        //   -> GetClassDefaults(BP_Enemy).DefaultName -> SpawnActor(BP_Enemy) -> set Name
        const string a3 = "/Game/Tests/UE5_0/CDO_Spawn_A";
        BlueprintTestHelper.CreateBlueprintActor(ctx, a3);
        var f3 = BlueprintTestHelper.CreateFunction(ctx, a3, "Make");
        var spawn3 = BlueprintTestHelper.AddNode(ctx, a3, "Make", "SpawnActorFromClass", 400, 0);
        BlueprintTestHelper.SetPinDefault(ctx, a3, spawn3.nodeId, "Class", "BP_Enemy");
        // Pending bridge capability: the GetClassDefaults node; SpawnActorFromClass itself
        // is supported and its Class pin takes the target class (see file header).
        BlueprintTestHelper.Connect(ctx, a3, f3.entryId, "then", spawn3.nodeId, "execute");
        BlueprintTestHelper.Connect(ctx, a3, spawn3.nodeId, "then", f3.resultId, "execute");
        BlueprintTestHelper.CompileAndSave(ctx, a3);

        // DSL path (copied from task doc)
        BlueprintTestHelper.ApplyDsl(ctx, "");

        await Task.CompletedTask;
    }
}